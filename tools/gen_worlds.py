#!/usr/bin/env python3
"""Builds one collecting world's catalog from its research list.

    python3 tools/gen_worlds.py sports          # one world
    python3 tools/gen_worlds.py all             # every world with a config

Each world has a config module in tools/worlds/<world>.py and a research list
docs/research/<list>. The list has five `== PAGE ==` sections (the binder pages,
one per platform), up to 50 lines each:

    rank. Name | Set | Year | Page | kind | tags | Team | Position | Wiki title

The config turns real names into parody names, picks kinds, values, blurbs and
appraisal tells. Output: scripts/data/catalog_<world>.gd (const ITEMS). Never
edit the output; edit the config or the list and run this again.
Pictures fetched by tools/fetch_world_art.py (assets/temp_test/<world>/<id>_*.png)
are picked up here too ("photo" / "scan" fields).
"""
import importlib.util
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONF_DIR = os.path.join(ROOT, "tools", "worlds")


def h(s, n):
    """Stable small hash, same idea as gen_collectibles.h."""
    v = 0
    for ch in s:
        v = (v * 131 + ord(ch)) % 1000003
    return v % max(1, n)


def slug(s):
    s = s.lower()
    for a, b in (("é", "e"), ("č", "c"), ("ć", "c"), ("í", "i"), ("á", "a"), ("ó", "o"), ("ê", "e")):
        s = s.replace(a, b)
    return re.sub(r"[^a-z0-9]+", "_", s).strip("_")[:30].strip("_")


def parse(path):
    section = ""
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"^== (.*) ==$", line)
        if m:
            section = m.group(1)
            continue
        m = re.match(r"^(\d+)\. (.*)$", line)
        if not m:
            continue
        parts = [p.strip() for p in m.group(2).split("|")]
        while len(parts) < 9:
            parts.append("")
        out.append({"rank": int(m.group(1)), "name": parts[0], "detail": parts[1], "year": int(parts[2]),
                    "code": parts[3], "kind": parts[4], "tags": [t for t in parts[5].split(",") if t],
                    "team": parts[6], "pos": parts[7], "wiki": parts[8], "section": section})
    return out


def tier_of(page_rows, r, grails):
    """Rarity from the position on its page: the top `grails` are GRAILS,
    the next ~12% rare, then uncommon to 40%, the rest common."""
    pos = page_rows.index(r)
    if pos < grails:
        return 3, pos / max(1, grails)
    rest = len(page_rows) - grails
    frac = (pos - grails) / max(1, rest - 1)
    if frac < 0.18:
        return 2, frac / 0.18
    if frac < 0.5:
        return 1, (frac - 0.18) / 0.32
    return 0, (frac - 0.5) / 0.5


def base_for(bands, tier, frac, key):
    lo, hi = bands[tier]
    v = hi - (hi - lo) * frac
    v *= 0.92 + (h(key, 17) / 100.0)
    return max(1, int(round(v)))


def val(v):
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, list):
        return "[" + ", ".join(val(x) for x in v) + "]"
    return str(v)


def load_conf(world):
    path = os.path.join(CONF_DIR, world + ".py")
    spec = importlib.util.spec_from_file_location("world_" + world, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build(world):
    conf = load_conf(world)
    rows = parse(os.path.join(ROOT, "docs", "research", conf.LIST))
    pages = {}
    for r in rows:
        pages.setdefault(r["code"], []).append(r)
    art_dir = os.path.join(ROOT, "assets", "temp_test", world)
    items = []
    ids = set()
    for r in rows:
        page = pages[r["code"]]
        tier, frac = tier_of(page, r, conf.GRAILS.get(r["code"], 1))
        d = conf.make_item(r, tier, frac, {"h": h, "slug": slug, "base_for": base_for})
        iid = d["id"]
        k = 2
        while iid in ids:
            iid = "%s_%d" % (d["id"], k)
            k += 1
        d["id"] = iid
        ids.add(iid)
        d["rank"] = r["rank"]
        d["page"] = r["section"]
        d["list"] = world
        d["year"] = r["year"]
        for kind in ("photo", "scan"):
            for ext in ("png", "jpg"):
                f = os.path.join(art_dir, "%s_%s.%s" % (iid, kind, ext))
                if os.path.exists(f):
                    d[kind] = "res://" + os.path.relpath(f, ROOT).replace(os.sep, "/")
        items.append(d)
    out = os.path.join(ROOT, "scripts", "data", "catalog_%s.gd" % world)
    lines = ["extends RefCounted",
             "## GENERATED by tools/gen_worlds.py %s from docs/research/%s." % (world, conf.LIST),
             "## Do not edit by hand: change tools/worlds/%s.py (or the list) and run it again." % world,
             "## No class_name (TV self-update): Catalog preloads this file.", "",
             "const ITEMS := ["]
    for d in items:
        lines.append("\t{" + ", ".join("%s: %s" % (json.dumps(k), val(v)) for k, v in d.items()) + "},")
    lines.append("]")
    lines.append("")
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    tiers = [0, 0, 0, 0]
    plats = {}
    for d in items:
        tiers[d["tier"]] += 1
        plats[d["plat"]] = plats.get(d["plat"], 0) + 1
    print(world, len(items), "tiers", tiers, plats, "pictures", sum(1 for d in items if "photo" in d or "scan" in d))
    if "--names" in sys.argv:
        for d in items:
            print(d["id"], "|", d["name"], "|", d["kind"], d["tier"], d["base"])
    return items


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    worlds = args or ["all"]
    if worlds == ["all"]:
        worlds = sorted(f[:-3] for f in os.listdir(CONF_DIR) if f.endswith(".py") and not f.startswith("_"))
    for w in worlds:
        build(w)


if __name__ == "__main__":
    main()
